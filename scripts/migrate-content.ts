#!/usr/bin/env node
/**
 * Phase 7 — One-time content migration (Static -> CMS)
 *
 * Reads the hardcoded public-site content snapshot (previously stored in
 * src/lib/content.ts and src/lib/diseases-content.ts) and writes it into the
 * corresponding Supabase tables:
 *   - services      -> upsert by `key`  (darman, shenasname, grooming, petshop)
 *   - doctors       -> upsert by `key`  (dr-tazik, dr-vasei, moghan-jahani)
 *   - diseases      -> upsert by (animal_type, name)  (requires migration 018's
 *                      unique index idx_diseases_animal_type_name)
 *   - testimonials  -> guarded insert (site testimonial cards)
 *   - site_content  -> upsert by `key` (clinic info + section copy, JSONB)
 *
 * The snapshot is embedded so this script stays runnable after the static
 * source files are deleted. It is idempotent — safe to re-run.
 *
 * Run:  node scripts/migrate-content.ts   (Node 22.6+/26 native TS support)
 * Uses .env.local (NEXT_PUBLIC_SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY).
 */
import dotenv from "dotenv";
import { createClient } from "@supabase/supabase-js";

dotenv.config({ path: ".env.local" });

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL!;
const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY!;

if (!supabaseUrl || !serviceRoleKey) {
  console.error("Missing NEXT_PUBLIC_SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY in .env.local");
  process.exit(1);
}

const supabase = createClient(supabaseUrl, serviceRoleKey, {
  auth: { autoRefreshToken: false, persistSession: false },
});

